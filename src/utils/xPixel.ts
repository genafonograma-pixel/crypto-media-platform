/**
 * X (Twitter) Pixel helper
 * Pixel ID: rjdgl
 *
 * Usage:
 *   import { trackBannerClick } from '../utils/xPixel';
 *   <a onClick={trackBannerClick} href="...">
 */

// Extend the global Window interface so TypeScript doesn't complain about `twq`
declare global {
  interface Window {
    twq?: (...args: any[]) => void;
  }
}

/**
 * Fire the X custom conversion event "Banner click".
 * Safe to call even if the pixel hasn't loaded yet — events are queued by the base code.
 */
export function trackBannerClick(): void {
  if (typeof window === 'undefined' || typeof window.twq !== 'function') return;
  // Custom conversion event ID generated by X Ads Manager for "Banner click"
  window.twq('event', 'tw-rjdgl-banner_click', {});
}
